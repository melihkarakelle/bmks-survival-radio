#!/usr/bin/env python3
"""Convert a black-on-white image to a 1-bit ST7565 page bitmap (C array).

Page format matches UI_DrawPixelBuffer: byte = 8 vertical pixels, LSB on top,
array[page][x]. Writes <out>.c and a 4x preview PNG of the full 128x64 screen.

Usage: logo2c.py src.png out_basename [--width 128 --height 40 --threshold 128]
"""
import argparse

from PIL import Image, ImageOps


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("out")
    ap.add_argument("--width", type=int, default=128)
    ap.add_argument("--height", type=int, default=40)
    ap.add_argument("--threshold", type=int, default=128)
    ap.add_argument("--name", default="BITMAP_SurvivalLogo")
    a = ap.parse_args()

    img = Image.open(a.src).convert("L")
    # crop to content, keep a 1px margin after scaling
    box = ImageOps.invert(img).point(lambda v: 255 if v > 40 else 0).getbbox()
    img = img.crop(box)
    img.thumbnail((a.width - 2, a.height - 2), Image.LANCZOS)
    canvas = Image.new("L", (a.width, a.height), 255)
    canvas.paste(img, ((a.width - img.width) // 2, (a.height - img.height) // 2))
    bw = canvas.point(lambda v: 0 if v < a.threshold else 255, "1")

    pages = a.height // 8
    rows = []
    for p in range(pages):
        row = []
        for x in range(a.width):
            b = 0
            for bit in range(8):
                if bw.getpixel((x, p * 8 + bit)) == 0:
                    b |= 1 << bit
            row.append(b)
        rows.append(row)

    with open(a.out + ".c", "w") as f:
        f.write(f"// generated by tools/logo2c.py from {a.src.split('/')[-1]}\n")
        f.write(f"const uint8_t {a.name}[{pages}][{a.width}] = {{\n")
        for row in rows:
            f.write("    {")
            f.write(", ".join(f"0x{b:02X}" for b in row))
            f.write("},\n")
        f.write("};\n")

    # preview: LCD-like colours, logo placed under the 8px status line
    lcd = Image.new("RGB", (128, 64), (170, 190, 150))
    ink = Image.new("RGB", (a.width, a.height), (20, 30, 20))
    lcd.paste(ink, (0, 8), ImageOps.invert(bw.convert("L")))
    lcd.resize((512, 256), Image.NEAREST).save(a.out + "_preview.png")
    print(f"wrote {a.out}.c ({pages}x{a.width} bytes) and {a.out}_preview.png")


if __name__ == "__main__":
    main()
