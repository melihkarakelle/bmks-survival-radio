#!/usr/bin/env python3
"""Build firmware/app/survival_manual.c from design/manual.txt (the F+6 manual).

"== TITLE" starts a topic, every other non-comment line is one screen row.
Titles share the status line with the "12/30" topic number, rows use the small font.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "manual.txt"
OUT = ROOT / "firmware" / "app" / "survival_manual.c"

TITLE_MAX = 12   # 7 px bold characters left of the topic number
ROW_MAX = 18     # 7 px small characters across 128 px


def main():
    topics, errors = [], []
    for n, raw in enumerate(SRC.read_text().splitlines(), 1):
        line = raw.rstrip()
        if line.startswith("#") or (not line and not topics):
            continue
        if line.startswith("== "):
            title = line[3:].strip()
            if len(title) > TITLE_MAX:
                errors.append(f"{n}: title over {TITLE_MAX}: {title!r}")
            topics.append([title])
        elif line:
            if len(line) > ROW_MAX:
                errors.append(f"{n}: row over {ROW_MAX} ({len(line)}): {line!r}")
            if any(c in line for c in '"\\') or not line.isascii():
                errors.append(f"{n}: unsupported character: {line!r}")
            topics[-1].append(line)
    if errors:
        sys.exit("\n".join(errors))

    out = [
        "/* Generated by tools/manual2c.py from design/manual.txt - edit the text there. */",
        "#ifdef ENABLE_SURVIVAL",
        "",
        "// Topics one after another: title, rows, each '\\0' terminated; an empty string ends",
        "// a topic, a second empty string (the final terminator) ends the manual.",
        "const char gSurvivalManual[] =",
    ]
    for topic in topics:
        out.append("    " + " ".join(f'"{s}\\0"' for s in topic[:1]))
        for row in topic[1:]:
            out.append(f'        "{row}\\0"')
        out.append('        "\\0"')
    out[-1] += ";"
    out += ["", "#endif", ""]
    OUT.write_text("\n".join(out))
    size = sum(len(s) + 1 for t in topics for s in t) + len(topics) + 1
    print(f"{len(topics)} topics, {sum(len(t) - 1 for t in topics)} rows, {size} bytes -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
